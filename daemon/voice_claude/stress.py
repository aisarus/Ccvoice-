"""Ударения для синтеза речи.

Русский синтез ошибается там, где ударение не выводится из написания:
в технических словах, в заимствованиях и в омографах. На слух это звучит
хуже, чем робот, — это звучит как чужой язык.

Разметка внутри одна: знак `+` перед ударной гласной. RHVoice понимает её
напрямую, а клиент при желании переводит в комбинирующее ударение U+0301
или снимает совсем — чем показывать текст со знаками, лучше показывать
чистый, а произносить размеченный.
"""
from __future__ import annotations

import re

MARK = "+"
ACUTE = "́"
VOWELS = "аеёиоуыэюяАЕЁИОУЫЭЮЯ"

# Слова, которые произносит сама оболочка, и техническая речь вокруг них.
# Односложные не нужны: там ошибиться негде.
WORDS = {
    "коммит": "комм+ит", "коммита": "комм+ита", "коммиты": "комм+иты",
    "коммитов": "комм+итов", "закоммитил": "закомм+итил",
    "репозиторий": "репозит+орий", "репозитория": "репозит+ория",
    "конфиг": "конф+иг", "конфига": "конф+ига", "конфиге": "конф+иге",
    "деплой": "депл+ой", "деплоя": "депл+оя",
    "токен": "т+окен", "токена": "т+окена", "токены": "т+окены",
    "сервер": "с+ервер", "сервера": "с+ервера", "сервере": "с+ервере",
    "ветка": "в+етка", "ветку": "в+етку", "ветке": "в+етке", "ветки": "в+етки",
    "модуль": "мод+уль", "модуля": "мод+уля",
    "скрипт": "скр+ипт", "скрипта": "скр+ипта",
    "бэкенд": "бэк+энд", "фронтенд": "фронт+энд",
    "откатил": "откат+ил", "откатила": "откат+ила",
    "запушил": "зап+ушил", "запушить": "зап+ушить",
    "мердж": "м+ердж", "линтер": "л+интер",
    "воркспейс": "ворксп+ейс",
    "логи": "л+оги", "логах": "л+огах", "логов": "л+огов",
    "тесты": "т+есты", "тестов": "т+естов", "тесты.": "т+есты.",
}

_WORD_RE = re.compile(r"[А-Яа-яЁё]+")


def mark(text: str) -> str:
    """Расставить знаки там, где мы точно знаем ударение."""
    def one(found: re.Match[str]) -> str:
        word = found.group(0)
        marked = WORDS.get(word.lower())
        if marked is None:
            return word
        return marked.capitalize() if word[0].isupper() else marked
    return _WORD_RE.sub(one, text)


def clean(text: str) -> str:
    """Убрать разметку: на экране знаки ударения только мешают."""
    return text.replace(MARK, "").replace(ACUTE, "")


def to_acute(text: str) -> str:
    """`комм+ит` → `коммит` с комбинирующим ударением после гласной."""
    out: list[str] = []
    index = 0
    while index < len(text):
        char = text[index]
        if char == MARK and index + 1 < len(text) and text[index + 1] in VOWELS:
            out.append(text[index + 1])
            out.append(ACUTE)
            index += 2
            continue
        out.append(char)
        index += 1
    return "".join(out)


def is_marked(text: str) -> bool:
    return MARK in text or ACUTE in text
